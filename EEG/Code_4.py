# Script location
SCRIPT_DIR = Path(__file__).resolve()
DATASET_DIR = SCRIPT_DIR.parent

# Shared data directories
RESULTS_DIR = DATASET_DIR / "results"
BEHAVIOR_DIR = DATASET_DIR / "behavior"

# Figure 4 outputs used to generate Figure 5
FIGURE_4_DIR = RESULTS_DIR / "Figure_4"

# Shared frequency vector
FREQ_FILE = DATASET_DIR / "ERSP_f.npy"

# Behavioral results
BEHAVIOR_FILE = BEHAVIOR_DIR / "Data_1.csv"

# Figure 5 output
FIGURE_5_DIR = RESULTS_DIR / "Figure_5"
OUTPUT_NAME = "Figure_5"

# Set to a number to force a symmetric colorbar range.
# Leave as None to derive the range from the displayed t-values.
COLORBAR_ABSMAX: float | None = None




