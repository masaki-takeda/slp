def plot_timeline(
    cluster_fmeans: dict[str, tuple[np.ndarray, np.ndarray]],
    star_positions: dict[str, int],
    shallow_cor1: float | None,
    deep_cor1: float | None,
    output_base: Path,
    colorbar_absmax: float | None = None,
    pupil95_shallow_trial: int | None = DEFAULT_PUPIL95_SHALLOW_TRIAL,
    pupil95_deep_trial: int | None = DEFAULT_PUPIL95_DEEP_TRIAL,
) -> None:  
    final_keys = [key for key in FINAL_ORDERED_KEYS if key in cluster_fmeans]
    if not final_keys:
        raise RuntimeError("No clusters available for plotting.")

    all_values = []
    for key in final_keys:
        _, values = cluster_fmeans[key]
        all_values.extend(values)
    all_values = np.asarray(all_values, dtype=float)

    if colorbar_absmax is not None:
        absmax = float(colorbar_absmax)
    else:
        # i.e., use the maximum positive trial-wise mean t-value as +/- limit.
        positives = all_values[np.isfinite(all_values) & (all_values > 0)]
        if len(positives) > 0:
            absmax = float(np.nanmax(positives))
        else:
            absmax = float(np.nanmax(np.abs(all_values)))

    if not np.isfinite(absmax) or absmax == 0:
        absmax = 1.0

    print(f"Colorbar range: {-absmax:.4f} to {absmax:.4f}")

    # Custom colormap: blue for negative, white near zero, red for positive.
    colors = [
        (0.0, "navy"),
        (0.25, "lightblue"),
        (0.4, "white"),
        (0.65, "white"),
        (0.88, "lightcoral"),
        (1.0, "firebrick"),
    ]
    cmap = LinearSegmentedColormap.from_list("custom_cmap", colors)
    norm = TwoSlopeNorm(vmin=-absmax, vcenter=0, vmax=absmax)

    segment_width = 3
    vline_width_trialRTB = 0.8
    vline_width_pupil95 = 0.6
    trialRTB_linestyle = (0, (5, 2.5))
    pupil95_linestyle = (0, (1, 3.5))

    plt.rcParams["font.size"] = "6"
    plt.rcParams["font.family"] = "Arial"

    fig_height = max(1.25, 0.26 * len(final_keys) + 0.6)
    plt.figure(figsize=(5.5, fig_height), dpi=600)
    ax = plt.gca()

    # Add vertical lines for mean RTB trial.
    if shallow_cor1 is not None:
        ax.axvline(
            shallow_cor1 + (segment_width / 2),
            color="#4169E1",
            linewidth=vline_width_trialRTB,
            linestyle=trialRTB_linestyle,
        )
    if deep_cor1 is not None:
        ax.axvline(
            deep_cor1 + (segment_width / 2),
            color="#FF8C00",
            linewidth=vline_width_trialRTB,
            linestyle= trialRTB_linestyle,
        )

    # Add vertical lines for reaching 95% of asymptotic pupil size.
    if pupil95_shallow_trial is not None:
        ax.axvline(
            trial_center_x(pupil95_shallow_trial),
            color="#4169E1",
            linewidth=vline_width_pupil95,
            linestyle=pupil95_linestyle,
            dash_capstyle="round",
        )
    if pupil95_deep_trial is not None:
        ax.axvline(
            trial_center_x(pupil95_deep_trial),
            color="#FF8C00",
            linewidth=vline_width_pupil95,
            linestyle=pupil95_linestyle,
            dash_capstyle="round",
        )

    for y_position, key in enumerate(final_keys):
        trial_zero_based, t_values = cluster_fmeans[key]
        trial_one_based = trial_zero_based + 1

        segments = []
        line_colors = []
        for t0, this_tval in zip(trial_one_based, t_values):
            segments.append([[t0, y_position], [t0 + 1, y_position]])
            line_colors.append(cmap(norm(this_tval)))

        lc = LineCollection(segments, colors=line_colors, linewidths=segment_width)
        ax.add_collection(lc)

    # Plot peak t-value markers.
    offset = 0.2
    for y_position, key in enumerate(final_keys):
        peak_trial_zero_based = star_positions[key]
        ax.plot(
            peak_trial_zero_based + (segment_width / 2),
            y_position - offset,
            marker="v",
            color="gray",
            markersize=2,
            markeredgewidth=0.3,
        )

    ax.set_yticks(range(len(final_keys)))
    ax.set_yticklabels([
        label.split("(")[0].replace("_", "\n").title()
        for label in final_keys
    ])

    ax.set_xlabel("Trials", fontsize=6)
    ax.set_ylabel("Clusters", fontsize=6)
    ax.set_ylim(-0.5, len(final_keys) - 0.5)
    ax.set_xlim(1, 91)

    xtick_labels = [1, 10, 20, 30, 40, 50, 60, 70, 80, 90]
    xtick_positions = [trial_center_x(t) for t in xtick_labels]
    ax.set_xticks(xtick_positions)
    ax.set_xticklabels([str(t) for t in xtick_labels])

    ax.invert_yaxis()

    ax.tick_params(
        axis="both",
        which="major",
        width=0.5,
        length=1.5,
        color="gray",
        direction="out",
    )

    for spine in ax.spines.values():
        spine.set_linewidth(0.5)
        spine.set_color("gray")

    legend_handles = []
    if shallow_cor1 is not None:
        legend_handles.append(
            Line2D([], [], color="#4169E1", linewidth=vline_width_trialRTB, linestyle=trialRTB_linestyle, label=r"Trial$_{RTB}$ in shallow-NREM group")
        )
    if deep_cor1 is not None:
        legend_handles.append(
            Line2D([], [], color="#FF8C00", linewidth=vline_width_trialRTB, linestyle=trialRTB_linestyle, label=r"Trial$_{RTB}$ in deep-NREM group")
        )
    if pupil95_shallow_trial is not None:
        legend_handles.append(
            Line2D(
                [], [],
                color="#4169E1",
                linewidth=vline_width_pupil95,
                linestyle=pupil95_linestyle,
                dash_capstyle="round",
                label="Reaching 95% of the asymptotic\npupil size in shallow-NREM group",
            )
        )
    if pupil95_deep_trial is not None:
        legend_handles.append(
            Line2D(
                [], [],
                color="#FF8C00",
                linewidth=vline_width_pupil95,
                linestyle=pupil95_linestyle,
                dash_capstyle="round",
                label="Reaching 95% of the asymptotic\npupil size in deep-NREM group",
            )
        )
    legend_handles.append(
        Line2D([], [], color="gray", marker="v", linestyle="None", markersize=3, markeredgewidth=0.5, label=r"$\it{t}$ value peak")
    )

    leg = ax.legend(handles=legend_handles, loc="upper right", fontsize=5, frameon=True)
    leg.get_frame().set_linewidth(0.3)

    sm = plt.cm.ScalarMappable(cmap=cmap, norm=norm)
    cbar = plt.colorbar(sm, ax=ax)
    cbar.ax.tick_params(width=0.3, length=1.5, direction="out", labelsize=5)
    cbar.outline.set_linewidth(0.3)
    cbar.outline.set_edgecolor("black")
    cbar.set_label(r"$\it{t}$ value", rotation=270, labelpad=12, fontsize=6)

    output_base.parent.mkdir(parents=True, exist_ok=True)
    plt.savefig(output_base.with_suffix(".png"), bbox_inches="tight")
    plt.savefig(output_base.with_suffix(".pdf"), bbox_inches="tight")
    plt.savefig(output_base.with_suffix(".svg"), bbox_inches="tight")
    plt.close()


# =============================================================================
# Main
# =============================================================================

def main() -> None:

    # Check the frequency vector
    if not FREQ_FILE.is_file():
        raise FileNotFoundError(
            f"Frequency file not found: {FREQ_FILE}"
        )

    # Check Figure 4 results
    if not FIGURE_4_DIR.is_dir():
        raise FileNotFoundError(
            f"Figure 4 results not found: {FIGURE_4_DIR}\n"
            "Run Figure_4_S5_S6_permutation_test_and_heatmap.py first."
        )

    # Check behavioral data
    if not BEHAVIOR_FILE.is_file():
        raise FileNotFoundError(
            f"Behavior file not found: {BEHAVIOR_FILE}"
        )

    behavior_file = BEHAVIOR_FILE

    ersp_f = np.load(FREQ_FILE, allow_pickle=True)
    broad = define_broad_indices(ersp_f)
    freq_axis = ersp_f[broad]

    print(f"Figure 4 results: {FIGURE_4_DIR}")
    print(f"Frequency file: {FREQ_FILE}")
    print(f"Behavior file: {BEHAVIOR_FILE}")
    print(f"Figure 5 output: {FIGURE_5_DIR}")


    cluster_fmeans: dict[str, tuple[np.ndarray, np.ndarray]] = {}
    star_positions: dict[str, int] = {}

    print("\nDetected displayed clusters:")
    for region in REGIONS:
        mask_file = FIGURE_4_DIR / f"deep_cluster_mask_{region.lower()}.npy"
        if not mask_file.is_file():
            raise FileNotFoundError(
                f"Missing cluster mask: {mask_file}"
            )

        mask = np.load(mask_file, allow_pickle=True)
        if mask.ndim != 2:
            raise ValueError(
                f"{mask_file} should be 2D: frequency x trial. Got {mask.shape}."
            )

        if mask.shape[0] != len(freq_axis):
            raise ValueError(
                f"Frequency dimension mismatch for {mask_file}: mask has {mask.shape[0]}, "
                f"but broad frequency axis has {len(freq_axis)}."
            )

        components = extract_components_from_mask(mask)
        named_components = assign_cluster_labels(region, components, freq_axis)

        for name, component in named_components.items():
            trials, values = component_to_trial_mean(component)
            cluster_fmeans[name] = (trials, values)
            star_positions[name] = choose_peak_trial(trials, values)

            f_low = float(freq_axis[component["freq_start_idx"]])
            f_high = float(freq_axis[component["freq_end_idx"]])
            print(
                f"  {name}: trials {component['trial_start'] + 1}-{component['trial_end'] + 1}, "
                f"{f_low:.2f}-{f_high:.2f} Hz, mean t = {component['mean_t']:.3f}"
            )

    missing_expected = [
        key for key in FINAL_ORDERED_KEYS if key not in cluster_fmeans
    ]
    if missing_expected:
        print("\nWARNING: these expected displayed clusters were not found:")
        for key in missing_expected:
            print(f"  - {key}")

    shallow_cor1, deep_cor1 = load_rtb_lines(behavior_file)

    output_base = FIGURE_5_DIR / OUTPUT_NAME
    plot_timeline(
        cluster_fmeans=cluster_fmeans,
        star_positions=star_positions,
        shallow_cor1=shallow_cor1,
        deep_cor1=deep_cor1,
        output_base=output_base,
        colorbar_absmax=COLORBAR_ABSMAX,
        pupil95_shallow_trial=DEFAULT_PUPIL95_SHALLOW_TRIAL,
        pupil95_deep_trial=DEFAULT_PUPIL95_DEEP_TRIAL,
    )

    print("\nSaved timeline figures:")
    print(f"  {output_base.with_suffix('.png')}")
    print(f"  {output_base.with_suffix('.pdf')}")
    print(f"  {output_base.with_suffix('.svg')}")


if __name__ == "__main__":
    main()
