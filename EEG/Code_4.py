"""
Plot Figure 5: Timeline of significant EEG clusters.

This script generates the timeline of significant EEG clusters
identified in the full-trial analysis (Figure 4).

The timeline shows:
- Significant clusters in the deep-NREM group.
- Trial-wise mean t-values within each cluster.
- Peak t-value positions.
- Mean Trial_RTB for the shallow-NREM and deep-NREM groups.
- Trials at which pupil size reaches 95% of its asymptotic value.

Input data
----------
SLP/
    ERSP_f.npy

    behavior/
        Data_1.csv

    results/
        Figure_4/
            deep_cluster_mask_frontal.npy
            deep_cluster_mask_parietal.npy
            deep_cluster_mask_temporal.npy
            deep_cluster_mask_occipital.npy

The cluster masks are generated by:
    Figure_4_S5_S6_permutation_test_and_heatmap.py

Each mask contains t-values for displayed significant clusters
and NaN values elsewhere.

Output
------
SLP/
    results/
        Figure_5/
            Figure_5.png
            Figure_5.pdf
            Figure_5.svg

Notes
-----
The pupil-95 trial values were calculated using the method
described in the manuscript and are specified in this script.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.collections import LineCollection
from matplotlib.colors import TwoSlopeNorm, LinearSegmentedColormap
from matplotlib.lines import Line2D
from scipy import ndimage


# =============================================================================
# Configuration
# =============================================================================

SHALLOW_IDS = [
    "Sub01", "Sub03", "Sub04", "Sub05", "Sub09", "Sub12", "Sub13",
    "Sub24", "Sub25", "Sub26", "Sub28", "Sub30", "Sub32", "Sub37",
    "Sub41", "Sub47", "Sub50", "Sub54", "Sub55", "Sub62", "Sub64",
]

DEEP_IDS = [
    "Sub02", "Sub06", "Sub08", "Sub15", "Sub17", "Sub18", "Sub21",
    "Sub22", "Sub29", "Sub31", "Sub36", "Sub38", "Sub39", "Sub40",
    "Sub43", "Sub45", "Sub46", "Sub48", "Sub51", "Sub53", "Sub59",
    "Sub61", "Sub63",
]

REGIONS = ["Frontal", "Parietal", "Temporal", "Occipital"]

# Labels and plotting order of the five displayed significant clusters.
FINAL_ORDERED_KEYS = [
    "frontal_delta/theta",
    "parietal_alpha",
    "parietal_beta2",
    "temporal_theta/alpha",
    "occipital_alpha",
]

# This matches the heatmap display rule in the permutation script:
# time_span >= 3 means at least 4 unique trials.
MIN_UNIQUE_TRIALS = 4

# Trials at which the fitted pupil-size curve reaches 95% of the asymptotic value.
# These values were calculated outside this repository using the procedure
# described in the manuscript Methods and are entered here as final values.
# They are 1-indexed trial numbers.
DEFAULT_PUPIL95_SHALLOW_TRIAL = 20
DEFAULT_PUPIL95_DEEP_TRIAL = 25


def trial_center_x(trial_one_indexed: int | float) -> float:
    """Return the x-position at the center of a 1-indexed trial bin.

    Trial n is drawn as the segment [n, n+1], so its center is n + 0.5.
    This also makes the x-tick label for Trial 20 align with the Trial-20
    pupil-95 vertical line.
    """
    return float(trial_one_indexed) + 0.5


